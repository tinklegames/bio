function render() {
  const list = $('#projectList');
  const query = $('#search').value.trim().toLowerCase();

  list.replaceChildren();

  const projects = CONFIG.projects.filter(project => {
    const matchesStatus =
      current === 'all' || project.status === current;

    const matchesSearch =
      project.name.toLowerCase().includes(query);

    return matchesStatus && matchesSearch;
  });

  if (!projects.length) {
    const empty = document.createElement('p');
    empty.className = 'modal-sub';
    empty.textContent = 'nothing found here yet.';
    list.append(empty);
    return;
  }

  projects.forEach((project, index) => {
    const playable =
      project.status === 'playable' && !!project.url;

    const card = document.createElement(
      playable ? 'a' : 'article'
    );

    card.className = 'project port-card';
    card.style.setProperty('--index', index);

    if (playable) {
      card.href = project.url;
      card.target = '_blank';
      card.rel = 'noopener noreferrer';

      card.classList.add('port-clickable');

      card.setAttribute(
        'aria-label',
        'Play ' + project.name
      );

      card.addEventListener('click', event => {
        if (
          event.button !== 0 ||
          event.ctrlKey ||
          event.metaKey ||
          event.shiftKey ||
          event.altKey
        ) return;

        event.preventDefault();
        openGame(project);
      });
    } else {
      card.classList.add('port-unreleased');
    }

    if (project.image) {
      const image = document.createElement('img');

      image.className = 'port-cover';
      image.src = project.image;
      image.alt = '';
      image.loading = 'lazy';

      image.onerror = () => {
        image.style.display = 'none';
      };

      card.append(image);
    }

    const overlay = document.createElement('div');
    overlay.className = 'port-overlay';
    card.append(overlay);

    const content = document.createElement('div');
    content.className = 'port-content';

    const title = document.createElement('h3');
    title.className = 'port-title';
    title.textContent = project.name;

    content.append(title);
    card.append(content);

    if (project.date) {
      const date = document.createElement('span');
      date.className = 'port-date';
      date.textContent = project.date;
      card.append(date);
    }

    list.append(card);
  });
}

function openModal(which) {
  lastFocus = document.activeElement;
  mode = which;

  $('#modalTitle').innerHTML =
    which === 'ports'
      ? 'my ports<span class="accent">.</span>'
      : 'about me<span class="accent">.</span>';

  $('#portsContent').classList.toggle(
    'hidden',
    which !== 'ports'
  );

  $('#aboutContent').classList.toggle(
    'hidden',
    which !== 'about'
  );

  $('#modal').classList.remove('hidden', 'closing');
  $('#modal').setAttribute('aria-hidden', 'false');

  document.body.style.overflow = 'hidden';

  if (which === 'ports') render();

  $('#closeBtn').focus();
}

function closeModal() {
  const modal = $('#modal');

  if (
    modal.classList.contains('hidden') ||
    modal.classList.contains('closing')
  ) return;

  modal.classList.add('closing');
  modal.setAttribute('aria-hidden', 'true');

  document.body.style.overflow = '';

  setTimeout(() => {
    modal.classList.add('hidden');
    modal.classList.remove('closing');
    lastFocus?.focus();
  }, 280);
}

$('#portsBtn').addEventListener(
  'click',
  () => openModal('ports')
);

$('#aboutBtn').addEventListener(
  'click',
  () => openModal('about')
);

$('#closeBtn').addEventListener('click', closeModal);

document.querySelector('[data-close]')
  .addEventListener('click', closeModal);

document.addEventListener('keydown', event => {
  const modal = $('#modal');

  if (
    event.key === 'Escape' &&
    !modal.classList.contains('hidden')
  ) {
    closeModal();
  }

  if (
    event.key === 'Tab' &&
    !modal.classList.contains('hidden')
  ) {
    const nodes = [
      ...modal.querySelectorAll(
        'button:not([disabled]),input,a[href]'
      )
    ].filter(element => element.offsetParent !== null);

    if (!nodes.length) return;

    const first = nodes[0];
    const last = nodes[nodes.length - 1];

    if (
      event.shiftKey &&
      document.activeElement === first
    ) {
      event.preventDefault();
      last.focus();
    } else if (
      !event.shiftKey &&
      document.activeElement === last
    ) {
      event.preventDefault();
      first.focus();
    }
  }
});

$('#search').addEventListener('input', render);

